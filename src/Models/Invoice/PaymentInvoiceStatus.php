<?php

namespace Crm\InvoicesModule\Models\Invoice;

use Crm\InvoicesModule\Models\BillingDataProviderInterface;

/**
 * Answers "what can be done about this payment's invoice, and if nothing, why".
 *
 * Built exclusively by PaymentInvoiceStatusResolver — do not construct this outside of it, and do not
 * re-derive any of these booleans elsewhere.
 */
final class PaymentInvoiceStatus
{
    public function __construct(
        public readonly ?BillingDataProviderInterface $billingProvider,
        public readonly bool $invoiceExists,
        public readonly bool $invoiceable,
        public readonly bool $periodExpired,
        public readonly bool $hasInvoiceAddress,
        public readonly ?string $blockedReasonKey,
    ) {
    }

    /**
     * The invoice is billed by an external provider (e.g. Stripe) instead of being generated by the CRM.
     */
    public function isExternal(): bool
    {
        return $this->billingProvider !== null;
    }

    /**
     * An invoice already exists and can be downloaded right now.
     */
    public function isDownloadable(): bool
    {
        return $this->invoiceExists || ($this->isExternal() && $this->invoiceable);
    }

    /**
     * No invoice exists yet, but generating one on demand will succeed.
     */
    public function isGeneratable(): bool
    {
        return !$this->isDownloadable()
            && !$this->isExternal()
            && $this->invoiceable
            && $this->hasInvoiceAddress;
    }
}
